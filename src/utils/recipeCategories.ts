import { Recipe, RecipeCategory, RECIPE_CATEGORIES } from '../types';

export function detectRecipeCategory(name?: string, ingredients?: string[]): RecipeCategory {
  const nameLower = (name || '').toLowerCase();
  const allText = `${nameLower} ${(ingredients || []).join(' ')}`.toLowerCase();

  // 1. Салаты (проверяем в первую очередь по названию, чтобы салат с курицей попадал в Салаты)
  if (
    /салат|цезарь|оливье|винегрет|греческий|мимоза|селедка под шубой|капрезе|коулсло|свекольник|рукола|шпинат|айсберг/i.test(
      nameLower
    )
  ) {
    return 'Салаты';
  }

  // 2. Завтрак (по названию)
  if (
    /завтрак|омлет|яичниц|сырник|каша|овсянк|блин|оладь|вафл|гранол|тост|скрэмбл|пашот|бенедикт|мюсли|панкейк/i.test(
      nameLower
    )
  ) {
    return 'Завтрак';
  }

  // 3. Десерты, перекус (по названию)
  if (
    /десерт|торт|пирог|пирожн|чизкейк|печень|кекс|маффин|брауни|булочк|круассан|конфет|шоколад|морожен|смузи|мусс|парфе|тирамису|перекус|батончик|чипс|сэндвич|бутерброд|шаурма|ролл|лаваш|снек|гренки/i.test(
      nameLower
    )
  ) {
    return 'Десерты, перекус';
  }

  // 4. Рыба и морепродукты (по названию или ингредиентам)
  if (
    /рыб|лосос|семг|форел|тунец|треск|судак|минтай|скумбри|сельдь|селедк|горбуш|кета|сибас|дорад|хек|камбал|карп|окунь|креветк|кальмар|миди|осьминог|краб|морепродукт|уха/i.test(
      nameLower
    )
  ) {
    return 'Рыба';
  }

  // 5. Курица и птица (по названию)
  if (
    /куриц|курин|цыпленок|цыплёнок|индейк|утка|утк|гусь|крылышк|голен|окорочок|наггетс|филе кур|куриное/i.test(
      nameLower
    )
  ) {
    return 'Курица';
  }

  // 6. Мясо (по названию)
  if (
    /мяс|говядин|свинин|баранин|фарш|телятин|стейк|котлет|бефстроганов|гуляш|буженин|ребрышк|рёбрышк|бекон|ветчин|карбонад|колбас|сосиск|люля|шашлык|паштет|фрикадельк|тефтел/i.test(
      nameLower
    )
  ) {
    return 'Мясо';
  }

  // Проверка по ингредиентам
  if (
    /рыб|лосос|семг|форел|тунец|треск|судак|минтай|скумбри|сельдь|селедк|горбуш|кета|сибас|дорад|хек|камбал|карп|окунь|креветк|кальмар|миди|осьминог|краб|морепродукт/i.test(
      allText
    )
  ) {
    return 'Рыба';
  }

  if (
    /куриц|курин|цыпленок|цыплёнок|индейк|утка|гусь|крылышк|голен|окорочок|наггетс|филе кур|куриное/i.test(
      allText
    )
  ) {
    return 'Курица';
  }

  if (
    /мяс|говядин|свинин|баранин|фарш|телятин|стейк|котлет|бефстроганов|гуляш|буженин|ребрышк|рёбрышк|бекон|ветчин|карбонад|колбас|сосиск|люля|шашлык/i.test(
      allText
    )
  ) {
    return 'Мясо';
  }

  if (/яйца|хлопь|творог|творожн|овсян/i.test(allText)) {
    return 'Завтрак';
  }

  if (/салат/i.test(allText)) {
    return 'Салаты';
  }

  return 'Завтрак';
}

export function getRecipeCategory(recipe: Partial<Recipe>): RecipeCategory {
  if (recipe.category && (RECIPE_CATEGORIES as readonly string[]).includes(recipe.category)) {
    return recipe.category;
  }
  return detectRecipeCategory(recipe.name, recipe.ingredients);
}
